#!/usr/bin/env node

/**
 * ecosystem-report.mjs — Monthly ecosystem health report.
 *
 * Usage:
 *   node scripts/ecosystem-report.mjs
 *
 * Generates a report covering:
 *   1. Registry stats (pack count, category distribution)
 *   2. i18n coverage trends
 *   3. Target runtime status
 *   4. Community contribution activity (if GITHUB_TOKEN available)
 *   5. Competitor landscape snapshot
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

// Load data
const catalog = JSON.parse(readFileSync(resolve(root, 'registry/catalog.json'), 'utf8'));
const i18nConfig = JSON.parse(readFileSync(resolve(root, 'i18n/config.json'), 'utf8'));
const packs = catalog.packs;

const categories = [...new Set(packs.map(p => p.category))].sort();
const targets = [...new Set(packs.flatMap(p => p.targets))].sort();

// i18n stats
const i18nStats = {};
for (const lang of i18nConfig.languages) {
  const filePath = resolve(root, `i18n/${lang}/catalog-descriptions.json`);
  if (existsSync(filePath)) {
    const data = JSON.parse(readFileSync(filePath, 'utf8'));
    const translated = Object.values(data).filter(v => !v._todo).length;
    i18nStats[lang] = { translated, total: packs.length, pct: ((translated / packs.length) * 100).toFixed(1) };
  } else {
    i18nStats[lang] = { translated: 0, total: packs.length, pct: '0.0' };
  }
}

// Known competitors / related projects for tracking
const competitors = [
  { name: 'agentic', repo: 'transitive-bullshit/agentic', description: 'AI agent standard library' },
  { name: 'goose', repo: 'block/goose', description: 'AI agent framework' },
  { name: 'claude-engineer', repo: 'Doriandarko/claude-engineer', description: 'Claude-based coding agent' },
  { name: 'aider', repo: 'paul-gauthier/aider', description: 'AI pair programming' },
  { name: 'continue', repo: 'continuedev/continue', description: 'AI code assistant IDE extension' }
];

// Target runtime docs for freshness tracking
const runtimeDocs = [
  { target: 'claude-code', url: 'https://docs.anthropic.com/en/docs/claude-code', notes: 'Skills directory format' },
  { target: 'codex', url: 'https://github.com/openai/codex', notes: 'AGENTS.md convention' },
  { target: 'github-copilot', url: 'https://docs.github.com/en/copilot', notes: 'Custom instructions' },
  { target: 'cursor', url: 'https://docs.cursor.com', notes: '.cursorrules format' },
  { target: 'opencode', url: 'https://github.com/opencode-ai/opencode', notes: 'Skills directory' }
];

// Generate report
const date = new Date().toISOString().split('T')[0];
const report = [
  `# Ecosystem Health Report — ${date}`,
  '',
  '## Registry Stats',
  '',
  `| Metric | Value |`,
  `|--------|-------|`,
  `| Total packs | ${packs.length} |`,
  `| Categories | ${categories.length} |`,
  `| Targets | ${targets.length} |`,
  `| i18n languages | ${i18nConfig.languages.length} |`,
  '',
  '### Category Breakdown',
  '',
  ...categories.map(c => `- **${c}**: ${packs.filter(p => p.category === c).length} packs`),
  '',
  '## i18n Coverage',
  '',
  '| Language | Coverage | Status |',
  '|----------|----------|--------|',
  ...i18nConfig.languages.map(lang => {
    const s = i18nStats[lang];
    const status = parseFloat(s.pct) >= i18nConfig.completionThreshold * 100 ? '✅' : '⚠️';
    return `| ${lang} | ${s.pct}% (${s.translated}/${s.total}) | ${status} |`;
  }),
  '',
  '## Target Runtime Status',
  '',
  'These runtimes should be periodically checked for breaking changes:',
  '',
  '| Target | Documentation | Watch For |',
  '|--------|--------------|-----------|',
  ...runtimeDocs.map(r => `| ${r.target} | [docs](${r.url}) | ${r.notes} |`),
  '',
  '## Competitor Landscape',
  '',
  'Projects in the AI agent tooling space to monitor:',
  '',
  '| Project | Repository | Focus |',
  '|---------|-----------|-------|',
  ...competitors.map(c => `| ${c.name} | [${c.repo}](https://github.com/${c.repo}) | ${c.description} |`),
  '',
  '## Action Items',
  '',
  '- [ ] Check each target runtime for convention changes',
  '- [ ] Review competitor releases for feature parity',
  '- [ ] Address any i18n coverage below threshold',
  '- [ ] Review community PRs and issues backlog',
  '- [ ] Update pack content for any stale entries',
  '',
  '---',
  '*Generated by `scripts/ecosystem-report.mjs`*',
  ''
].join('\n');

writeFileSync(resolve(root, 'docs/ecosystem-report.md'), report, 'utf8');

// Console output
console.log(`═══ Ecosystem Health Report (${date}) ═══\n`);
console.log(`Registry: ${packs.length} packs, ${categories.length} categories, ${targets.length} targets`);
console.log(`i18n: ${i18nConfig.languages.length} languages configured`);
console.log(`Competitors tracked: ${competitors.length}`);
console.log(`\nReport written to docs/ecosystem-report.md`);

// GitHub Actions output
if (process.env.GITHUB_OUTPUT) {
  writeFileSync(process.env.GITHUB_OUTPUT, `report_path=docs/ecosystem-report.md\n`, { flag: 'a' });
}
