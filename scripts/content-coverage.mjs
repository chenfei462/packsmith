#!/usr/bin/env node

/**
 * content-coverage.mjs — Generates a content coverage matrix showing
 * pack distribution across categories, languages, and targets.
 *
 * Usage:
 *   node scripts/content-coverage.mjs
 *
 * Output:
 *   - Console summary
 *   - docs/content-coverage.md (markdown report)
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

// Load data
const catalog = JSON.parse(readFileSync(resolve(root, 'registry/catalog.json'), 'utf8'));
const i18nConfig = JSON.parse(readFileSync(resolve(root, 'i18n/config.json'), 'utf8'));
const packs = catalog.packs;

// Load translations
const translations = {};
for (const lang of i18nConfig.languages) {
  const filePath = resolve(root, `i18n/${lang}/catalog-descriptions.json`);
  if (existsSync(filePath)) {
    const data = JSON.parse(readFileSync(filePath, 'utf8'));
    // Count only non-TODO entries
    translations[lang] = Object.entries(data).filter(([, v]) => !v._todo).length;
  } else {
    translations[lang] = 0;
  }
}

// Compute matrices
const categories = [...new Set(packs.map(p => p.category))].sort();
const targets = [...new Set(packs.flatMap(p => p.targets))].sort();

// Category × count
const categoryCount = {};
for (const cat of categories) {
  categoryCount[cat] = packs.filter(p => p.category === cat).length;
}

// Target × count
const targetCount = {};
for (const tgt of targets) {
  targetCount[tgt] = packs.filter(p => p.targets.includes(tgt)).length;
}

// Category × Target matrix
const catTargetMatrix = {};
for (const cat of categories) {
  catTargetMatrix[cat] = {};
  for (const tgt of targets) {
    catTargetMatrix[cat][tgt] = packs.filter(p => p.category === cat && p.targets.includes(tgt)).length;
  }
}

// i18n coverage
const totalPacks = packs.length;
const i18nCoverage = {};
for (const lang of i18nConfig.languages) {
  i18nCoverage[lang] = {
    translated: translations[lang],
    total: totalPacks,
    pct: ((translations[lang] / totalPacks) * 100).toFixed(1)
  };
}

// Identify gaps
const gaps = [];

// Category gaps (any category with < 4 packs)
for (const [cat, count] of Object.entries(categoryCount)) {
  if (count < 4) {
    gaps.push(`Category "${cat}" has only ${count} pack(s) — consider adding more`);
  }
}

// i18n gaps
for (const [lang, data] of Object.entries(i18nCoverage)) {
  if (parseFloat(data.pct) < i18nConfig.completionThreshold * 100) {
    gaps.push(`Language "${lang}" is at ${data.pct}% translation coverage (threshold: ${(i18nConfig.completionThreshold * 100).toFixed(0)}%)`);
  }
}

// Regional ecosystem gaps
const regionalPacks = packs.filter(p =>
  p.tags?.some(t => ['wechat', 'alipay', 'line', 'kakao', 'naver', 'alibaba', 'tencent'].includes(t))
);
if (regionalPacks.length === 0) {
  gaps.push('No regional ecosystem packs (WeChat, Alipay, LINE, Kakao, etc.) — critical for Asian markets');
}

// Generate report
function categoryLabel(cat) {
  return cat.split('-').map(w => w[0].toUpperCase() + w.slice(1)).join(' ');
}

const report = [
  '# Content Coverage Report',
  '',
  `> Auto-generated on ${new Date().toISOString().split('T')[0]}`,
  '',
  '## Summary',
  '',
  `| Metric | Value |`,
  `|--------|-------|`,
  `| Total packs | ${totalPacks} |`,
  `| Categories | ${categories.length} |`,
  `| Supported targets | ${targets.length} |`,
  `| Languages (i18n) | ${i18nConfig.languages.length + 1} |`,
  '',
  '## Category Distribution',
  '',
  '| Category | Packs |',
  '|----------|-------|',
  ...categories.map(c => `| ${categoryLabel(c)} | ${categoryCount[c]} |`),
  '',
  '## Target Coverage',
  '',
  '| Target | Packs Supporting |',
  '|--------|-----------------|',
  ...targets.map(t => `| ${t} | ${targetCount[t]} |`),
  '',
  '## Category × Target Matrix',
  '',
  `| Category | ${targets.join(' | ')} |`,
  `|----------|${targets.map(() => '---').join('|')}|`,
  ...categories.map(cat =>
    `| ${categoryLabel(cat)} | ${targets.map(t => catTargetMatrix[cat][t]).join(' | ')} |`
  ),
  '',
  '## i18n Coverage',
  '',
  '| Language | Translated | Total | Coverage |',
  '|----------|-----------|-------|----------|',
  `| English (en) | ${totalPacks} | ${totalPacks} | 100.0% |`,
  ...i18nConfig.languages.map(lang =>
    `| ${lang} | ${i18nCoverage[lang].translated} | ${i18nCoverage[lang].total} | ${i18nCoverage[lang].pct}% |`
  ),
  '',
  '## Identified Gaps',
  '',
  gaps.length > 0
    ? gaps.map(g => `- ⚠️ ${g}`).join('\n')
    : '✅ No critical gaps identified.',
  '',
  '---',
  '*This report is auto-generated by `scripts/content-coverage.mjs`.*',
  ''
].join('\n');

// Write report
writeFileSync(resolve(root, 'docs/content-coverage.md'), report, 'utf8');

// Console output
console.log('═══ Content Coverage Summary ═══\n');
console.log(`Packs: ${totalPacks} across ${categories.length} categories`);
console.log(`Targets: ${targets.length} (${targets.join(', ')})`);
console.log(`Languages: en + ${i18nConfig.languages.join(', ')}`);
console.log('');

console.log('i18n coverage:');
for (const lang of i18nConfig.languages) {
  const bar = '█'.repeat(Math.round(parseFloat(i18nCoverage[lang].pct) / 10));
  console.log(`  ${lang}: ${bar} ${i18nCoverage[lang].pct}%`);
}

if (gaps.length > 0) {
  console.log(`\nGaps found: ${gaps.length}`);
  for (const g of gaps) console.log(`  ⚠ ${g}`);
}

console.log('\nReport written to docs/content-coverage.md');
